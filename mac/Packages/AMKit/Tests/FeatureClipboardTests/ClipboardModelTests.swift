@MainActor @Test func sendsAfterPhoneTurnsOnOnlyNewCopies() async {
    let (model, board, sent) = rig()
    await model.connected(phoneID: "P1", phoneName: "Pixel", shared: shared)
    await model.message(availability(false, .offByUser))
    // One copy looked at while off, one made while off that no poll saw yet.
    board.copy("seen while off")
    await model.poll()
    board.copy("made while off")
    await model.message(availability(true))
    await model.poll()
    #expect(sent.messages.isEmpty, "copies made while off are never sent")
