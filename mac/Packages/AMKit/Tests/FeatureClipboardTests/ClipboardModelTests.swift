@MainActor @Test func availabilityIsStored() async {
    let (model, _, _) = rig()
    await model.connected(phoneID: "P1", phoneName: "Pixel", shared: shared)
    #expect(model.phoneAvailability == nil)
    var a = AMFeatureAvailability()
    a.enabled = false
    a.reason = .offByUser
    await model.message(envelope(.clipboardAvailability, a))
    #expect(model.phoneAvailability == a)
    model.disconnected()
    #expect(model.phoneAvailability == nil)
}

