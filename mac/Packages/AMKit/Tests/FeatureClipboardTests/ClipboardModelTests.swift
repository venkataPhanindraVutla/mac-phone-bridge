@MainActor @Test func sendDisabledSendsNothing() async {
    let (model, board, sent) = rig(sendEnabled: false)
    await model.connected(phoneID: "P1", phoneName: "Pixel", shared: shared)
    board.copy("hello")
    await model.poll()
    #expect(sent.messages.isEmpty)
    // Switched off, the pasteboard is not even read.
    #expect(board.reads == 0)
    // Turning it on later does not send what was copied while it was off.
    model.sendEnabled = true
    await model.poll()
    #expect(sent.messages.isEmpty)
    board.copy("later")
    await model.poll()
    #expect(sent.messages.map(\.text) == ["later"])
}

@MainActor @Test func nothingIsSentAtConnect() async {
    let (model, board, sent) = rig()
    board.copy("copied before connecting")
    await model.connected(phoneID: "P1", phoneName: "Pixel", shared: shared)
    await model.poll()
    #expect(sent.messages.isEmpty)

    // Copied while disconnected: not sent at the next connect either.
    model.disconnected()
    board.copy("copied while apart")
    await model.connected(phoneID: "P1", phoneName: "Pixel", shared: shared)
    await model.poll()
    #expect(sent.messages.isEmpty)
}

@MainActor @Test func notSharedSendsNothing() async {
