import AMProtocol
import Foundation
import SwiftProtobuf
import Testing
@testable import FeatureClipboard

/// A pasteboard whose change count and types the test sets by hand.
@MainActor
private final class FakePasteboard: PasteboardAccess {
    var changeCount = 0
    var types: [String] = []
    var string: String?
    var writes: [String] = []
    var reads = 0
    /// Runs inside the next `readString()`, once: another app writing mid-read.
    var duringRead: (() -> Void)?

    func readString() -> String? {
        reads += 1
        if let hook = duringRead {
            duringRead = nil
            hook()
        }
        return string
    }

    func writeString(_ s: String) {
        writes.append(s)
        string = s
        types = ["public.utf8-plain-text"]
        changeCount += 1
    }

    /// What another app copying `text` looks like.
    func copy(_ text: String, types extra: [String] = []) {
        string = text
        types = ["public.utf8-plain-text"] + extra
        changeCount += 1
    }
}

@MainActor
private final class Sent {
    var messages: [(type: MessageType, text: String)] = []
}

@MainActor
private func rig(sendEnabled: Bool = true) -> (ClipboardModel, FakePasteboard, Sent) {
    let board = FakePasteboard()
    let sent = Sent()
    let model = ClipboardModel(
        pasteboard: board, sendEnabled: sendEnabled,
        send: { type, message in
            sent.messages.append((type, (message as? AMClipboardText)?.text ?? "?"))
        },
        // The tests call poll() themselves; the loop must not get in the way.
        interval: .seconds(3600))
    return (model, board, sent)
}

private let shared: Set<String> = ["status.v1", "clipboard.v1"]

private func envelope<M: SwiftProtobuf.Message>(_ type: MessageType, _ message: M) -> AMEnvelope {
    var e = AMEnvelope()
    e.channel = .clipboard
    e.type = type.rawValue
    e.payload = (try? message.serializedData()) ?? Data()
    return e
}

private func clipboardText(_ text: String) -> AMEnvelope {
    var t = AMClipboardText()
    t.text = text
    return envelope(.clipboardText, t)
}

@MainActor @Test func changedTextIsSent() async {
    let (model, board, sent) = rig()
    await model.connected(phoneID: "P1", phoneName: "Pixel", shared: shared)
    board.copy("hello")
    await model.poll()
    #expect(sent.messages.map(\.type) == [.clipboardText])
    #expect(sent.messages.map(\.text) == ["hello"])
}

@MainActor @Test func unchangedCountSendsNothing() async {
    let (model, board, sent) = rig()
    await model.connected(phoneID: "P1", phoneName: "Pixel", shared: shared)
    board.copy("hello")
    await model.poll()
    await model.poll()
    // Another text without a new count (nobody wrote the pasteboard) is not looked at.
    board.string = "other"
    await model.poll()
    #expect(sent.messages.map(\.text) == ["hello"])
}

@MainActor @Test func concealedTypeIsNotSent() async {
