@MainActor @Test func oversizedTextIsNotSent() async {
    let (model, board, sent) = rig()
    await model.connected(phoneID: "P1", phoneName: "Pixel", shared: shared)
    // "é" is two bytes in UTF-8: half as many characters as the cap is already one byte over.
    board.copy(String(repeating: "é", count: ClipboardModel.maxBytes / 2) + "x")
    await model.poll()
    #expect(sent.messages.isEmpty)
    // Exactly at the cap is fine.
    board.copy(String(repeating: "a", count: ClipboardModel.maxBytes))
    await model.poll()
    #expect(sent.messages.count == 1)
}

@MainActor @Test func textFromPhoneIsNotEchoed() async {
    let (model, board, sent) = rig()
    await model.connected(phoneID: "P1", phoneName: "Pixel", shared: shared)
    await model.message(clipboardText("from phone"))
    #expect(board.writes == ["from phone"])
    // Plain text only: no marker types.
    #expect(board.types == ["public.utf8-plain-text"])
    await model.poll() // the write moved the count
    #expect(sent.messages.isEmpty)
    // The same text copied again on the Mac is still the phone's text.
    board.copy("from phone")
    await model.poll()
    #expect(sent.messages.isEmpty)

    // acceptFromPhone (share.text) counts too.
    model.acceptFromPhone("shared")
    await model.poll()
    #expect(sent.messages.isEmpty)
    #expect(model.currentText() == "shared")
}

