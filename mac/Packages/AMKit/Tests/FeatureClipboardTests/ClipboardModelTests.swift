@MainActor @Test func pollLoopSendsWhileConnected() async throws {
    let board = FakePasteboard()
    let sent = Sent()
    let model = ClipboardModel(
        pasteboard: board, sendEnabled: true,
        send: { type, message in sent.messages.append((type, (message as? AMClipboardText)?.text ?? "?")) },
        interval: .milliseconds(10))
    await model.connected(phoneID: "P1", phoneName: "Pixel", shared: shared)
    board.copy("looped")
    for _ in 0..<200 where sent.messages.isEmpty { try await Task.sleep(for: .milliseconds(10)) }
    #expect(sent.messages.map(\.text) == ["looped"])
    model.disconnected()
    board.copy("after")
    try await Task.sleep(for: .milliseconds(100))
    #expect(sent.messages.map(\.text) == ["looped"])
}

@MainActor @Test func recopyAfterSendIsSent() async {
    let (model, board, sent) = rig()
    await model.connected(phoneID: "P1", phoneName: "Pixel", shared: shared)
    await model.message(clipboardText("X"))
    await model.poll()
    board.copy("Z")
    await model.poll()
    // The phone now has Z, so X goes again.
    board.copy("X")
    await model.poll()
    #expect(sent.messages.map(\.text) == ["Z", "X"])
}

