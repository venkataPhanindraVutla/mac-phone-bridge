import AMProtocol
import ConnectionCore
import CryptoKit
import Foundation
import Observation
import SwiftProtobuf

/// How an explicit "send the clipboard" ended (used by the share model and the menu).
public enum ClipboardSendOutcome: Equatable, Sendable { case sent, empty, tooLarge, notConnected }

/// Clipboard sync with the phone (SPEC section 14). While a phone that shares `clipboard.v1` is
/// connected, the Mac's pasteboard is polled; a copy made after connecting is sent as
/// `clipboard.text` unless it is a password manager's item, too large, or text the phone itself
/// put there. Text from the phone is written as plain text.
///
/// Ruling R22: a copy goes only while the phone reports `clipboard.availability` enabled. Before
/// the first availability of a connection, or while the phone's switch is off, nothing is sent,
/// and copies made then are never sent later (only copies made after it turns on go).
///
/// Clipboard text is never logged, nor its size or hash.
@MainActor
@Observable
public final class ClipboardModel: SessionFeature {
    public let messagePrefixes = ["clipboard."]

    /// The most a `ClipboardText.text` may be, in UTF-8 bytes.
    public static let maxBytes = 262_144
    /// Pasteboard markers (nspasteboard.org) of items that must never leave the Mac: passwords,
    /// one-off and generated items.
    public static let skippedTypes = [
        "org.nspasteboard.ConcealedType", "org.nspasteboard.TransientType", "org.nspasteboard.AutoGeneratedType",
    ]

    /// The Settings switch "Send Mac clipboard to the phone" (default on).
    public var sendEnabled: Bool
    /// The phone's last `clipboard.availability`; nil until the first one of this connection.
    public private(set) var phoneAvailability: AMFeatureAvailability?

    @ObservationIgnored private let pasteboard: any PasteboardAccess
    @ObservationIgnored private let send: @MainActor (MessageType, any SwiftProtobuf.Message & Sendable) async -> Void
    @ObservationIgnored private let interval: Duration
    /// True while a phone that shares `clipboard.v1` is connected.
    @ObservationIgnored private var active = false
    /// The change count already looked at; a poll acts only when it moves.
    @ObservationIgnored private var seenCount = 0
    /// The SHA-256 of the text the phone has now, as far as this session knows: set on every
    /// send and every receive, cleared on disconnect. Equal text is never sent to it again.
    @ObservationIgnored private var phoneHas: SHA256.Digest?
    @ObservationIgnored private var loop: Task<Void, Never>?

    public init(pasteboard: any PasteboardAccess, sendEnabled: Bool,
                send: @escaping @MainActor (MessageType, any SwiftProtobuf.Message & Sendable) async -> Void,
                interval: Duration = .milliseconds(500)) {
        self.pasteboard = pasteboard
        self.sendEnabled = sendEnabled
        self.send = send
        self.interval = interval
    }

    // MARK: SessionFeature

    public func connected(phoneID: String, phoneName: String, shared: Set<String>) async {
        stop()
        phoneAvailability = nil
        guard shared.contains("clipboard.v1") else { return }
        active = true
        // Only copies made from now on go across.
        seenCount = pasteboard.changeCount
        let interval = interval
        loop = Task { [weak self] in
            while !Task.isCancelled {
                try? await Task.sleep(for: interval)
                guard !Task.isCancelled, let self else { return }
                await self.poll()
            }
        }
    }

    public func disconnected() {
        stop()
        phoneAvailability = nil
        // The phone's clipboard may change while apart, and the next phone may be another one.
        phoneHas = nil
    }

    public func message(_ envelope: AMEnvelope) async {
        guard active else { return }
        switch MessageType(rawValue: envelope.type) {
        case .clipboardText:
            if let t = try? AMClipboardText(serializedBytes: envelope.payload) { acceptFromPhone(t.text) }
        case .clipboardAvailability:
            guard let a = try? AMFeatureAvailability(serializedBytes: envelope.payload) else { return }
            // Turned on: only copies made from now on go, not one made while it was off that
            // no poll has looked at yet (R22).
            if a.enabled, phoneAvailability?.enabled != true { seenCount = pasteboard.changeCount }
            phoneAvailability = a
        default:
            break
        }
    }

    public func forget(phoneID: String) async {}

    // MARK: clipboard

    /// One look at the pasteboard: sends its text when the change count moved and the text may go.
    public func poll() async {
        guard active else { return }
        let count = pasteboard.changeCount
        guard count != seenCount else { return }
        seenCount = count
        // Switched off, here or on the phone (R22): the pasteboard is not read, and turning it on
        // never sends what is there now.
        guard sendEnabled, phoneAvailability?.enabled == true,
              Set(pasteboard.types).isDisjoint(with: Self.skippedTypes) else { return }
        let text = pasteboard.readString()
        // Written while being read: the types checked may not be this text's (a password manager's
        // concealed item). The next tick sees the moved count and looks at it afresh.
        guard pasteboard.changeCount == count else { return }
        guard let text, !text.isEmpty, text.utf8.count <= Self.maxBytes else { return }
        let digest = SHA256.hash(data: Data(text.utf8))
        guard digest != phoneHas else { return }
        phoneHas = digest
        var message = AMClipboardText()
        message.text = text
        await send(.clipboardText, message)
    }

    /// Puts the phone's text on the pasteboard and remembers it, so it is not sent back.
    public func acceptFromPhone(_ text: String) {
        phoneHas = SHA256.hash(data: Data(text.utf8))
        pasteboard.writeString(text)
    }

    /// `text` was sent another way (`share.text`), and the phone put it on its clipboard: the
    /// same text copied on the Mac is not sent again.
    public func noteSentToPhone(_ text: String) {
        phoneHas = SHA256.hash(data: Data(text.utf8))
    }

    /// The pasteboard's text for an explicit send; nil when there is none. Skips no type: the
    /// user asked for it.
    public func currentText() -> String? {
        guard let text = pasteboard.readString(), !text.isEmpty else { return nil }
        return text
    }

    private func stop() {
        active = false
        loop?.cancel()
        loop = nil
    }
}
